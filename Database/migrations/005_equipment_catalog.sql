-- Справочник оборудования для окна карточки клапана (ValveWindow):
-- производители ЗРА и модели позиционеров/приводов. Раньше производители
-- были зашиты в ValveWindow.ui, а модели вводились свободным текстом.
--
-- Ключи естественные (текст), без суррогатных id: карточка клапана
-- (valve_snapshots) хранит производителя и модели тоже текстом, а импорт
-- чужой базы сливает справочник простым INSERT OR IGNORE по ключу.
-- COLLATE NOCASE — чтобы "SAMSON 3730" и "Samson 3730" не стали двумя
-- записями (SQLite сворачивает регистр только у латиницы).
--
-- source: 'builtin' — из файла "Позиционеры, приводы, модели клапанов"
-- (2026-11), 'user' — введено вручную в ValveWindow ("Ручной ввод").
CREATE TABLE catalog_manufacturers (
    name        TEXT NOT NULL COLLATE NOCASE PRIMARY KEY,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    source      TEXT NOT NULL DEFAULT 'builtin'
);

-- kind: 'positioner' | 'drive'.
-- manufacturer: '' — модель без производителя (ЭПП-300, ЭПП-1), видна при
-- любом выбранном производителе ЗРА.
-- dynamic_error: текст пункта comboBox_dinamicError ('1.5' — интеллектуальные,
-- '2.5' — электропневматические); у приводов всегда ''.
CREATE TABLE catalog_models (
    kind           TEXT NOT NULL,
    manufacturer   TEXT NOT NULL DEFAULT '' COLLATE NOCASE,
    dynamic_error  TEXT NOT NULL DEFAULT '',
    name           TEXT NOT NULL COLLATE NOCASE,
    sort_order     INTEGER NOT NULL DEFAULT 0,
    source         TEXT NOT NULL DEFAULT 'builtin',
    PRIMARY KEY (kind, manufacturer, dynamic_error, name)
);

