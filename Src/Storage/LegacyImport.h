#pragma once

#include <QString>

// Разовый перенос карточек клапанов, накопленных до перехода на БД
// (QSettings("MPPI", "Data"): реестр Windows / ~/.config на Linux), в
// Database/mpiplatform.db. Нужен, чтобы обновлённое приложение, придя на
// машину, где данные жили только в реестре, не "забыло" их: карточки
// становятся сессиями source='legacy' (см. HistoryWriter::importLegacyCards).
//
// Выполняется один раз на базу: флаг legacy_import_done лежит в app_state
// самой БД, поэтому перенос базы на другой компьютер не вызывает повторного
// импорта, а чистая база на компьютере со старым реестром — вызывает.
namespace LegacyImport {

struct Result {
    bool ran = false;      // true — импорт выполнялся в этом запуске (флаг был не выставлен)
    int imported = 0;      // сколько карточек перенесено
    QString error;         // непусто — не удалось, флаг НЕ выставлен, следующий запуск повторит
};

Result runOnce();

}
